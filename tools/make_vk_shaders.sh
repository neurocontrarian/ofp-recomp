#!/bin/sh
# Compiles src/linux/vk/*.{vert,frag} to SPIR-V as C arrays in
# src/linux/vk_shaders.h (committed: the build needs no shader compiler).
# glslangValidator: third_party/vk-tools (apt-get download glslang-tools).
set -e
P=$(cd "$(dirname "$0")/.." && pwd)
G=${GLSLANG:-$P/third_party/vk-tools/root/usr/bin/glslangValidator}
export LD_LIBRARY_PATH=$P/third_party/vk-tools/root/usr/lib/x86_64-linux-gnu
O=$P/src/linux/vk_shaders.h
T=$(mktemp -d)
echo "/* generated by tools/make_vk_shaders.sh from src/linux/vk: do not edit */" > "$O.tmp"
for f in "$P"/src/linux/vk/*.vert "$P"/src/linux/vk/*.frag; do
    n=$(basename "$f" | tr . _)
    "$G" -V --target-env vulkan1.3 -o "$T/$n.spv" "$f" >/dev/null
    python3 -I - "$T/$n.spv" "$n" >> "$O.tmp" <<'PY'
import sys
b = open(sys.argv[1], 'rb').read()
w = [int.from_bytes(b[i:i + 4], 'little') for i in range(0, len(b), 4)]
print('static const uint32_t spv_%s[%d] = {' % (sys.argv[2], len(w)))
for i in range(0, len(w), 8): print('    ' + ', '.join('0x%08x' % x for x in w[i:i + 8]) + ',')
print('};')
PY
done
mv "$O.tmp" "$O"
rm -rf "$T"
